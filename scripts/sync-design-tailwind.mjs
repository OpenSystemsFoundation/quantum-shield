import fs from 'node:fs';
import { lint } from '@google/design.md/linter';

const input = process.argv[2] ?? 'DESIGN.md';
const output = process.argv[3] ?? 'src/styles/tailwind-design.generated.mjs';

const source = fs.readFileSync(input, 'utf8');
const report = lint(source);

if (report.summary.errors > 0) {
  console.error(`Cannot generate Tailwind tokens: ${report.summary.errors} Design.md error(s).`);
  for (const finding of report.findings.filter((item) => item.severity === 'error')) {
    console.error(`- ${finding.path ? `${finding.path}: ` : ''}${finding.message}`);
  }
  process.exit(1);
}

if (!report.tailwindConfig.success) {
  console.error('Cannot generate Tailwind tokens: Tailwind emitter failed.');
  console.error(JSON.stringify(report.tailwindConfig, null, 2));
  process.exit(1);
}

const generated = `// Generated by scripts/sync-design-tailwind.mjs from ${input}.
// Do not edit by hand. Update DESIGN.md, then run npm run design:sync-tailwind.

export default ${JSON.stringify(report.tailwindConfig.data.theme.extend, null, 2)};
`;

fs.writeFileSync(output, generated, 'utf8');
console.log(`Synced ${input} -> ${output}`);
