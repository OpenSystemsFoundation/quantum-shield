#!/usr/bin/env bash
#
# Pull the Consumer Key of the QuantumShield Scanner External Client App
# from the given scratch org and update .env.local.
#
# Usage:  sfdx/fetch-key.sh [scratch-alias] [app-name]
#
set -euo pipefail

SCRATCH="${1:-qs-scan}"
APP_NAME="${2:-QuantumShield Scanner}"
SFDX_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SFDX_DIR/.." && pwd)"

SF_BIN="${SF_BIN:-sf}"
if ! command -v "$SF_BIN" >/dev/null 2>&1; then
  if [[ -x "/c/Users/jeffk/AppData/Roaming/npm/sf" ]]; then
    SF_BIN="/c/Users/jeffk/AppData/Roaming/npm/sf"
  else
    echo "sf CLI not found on PATH" >&2
    exit 1
  fi
fi

CONSUMER_KEY=$("$SF_BIN" data query \
  --target-org "$SCRATCH" \
  --use-tooling-api \
  -q "SELECT Id, OauthConsumerKey FROM ConnectedApplication WHERE Name='$APP_NAME' LIMIT 1" \
  --json 2>/dev/null | node -e "
const j = JSON.parse(require('fs').readFileSync(0, 'utf8'));
const r = j.result?.records?.[0];
if (!r) { console.error('No app named \"$APP_NAME\" found in org $SCRATCH'); process.exit(1); }
process.stdout.write(r.OauthConsumerKey || '');
")

if [[ -z "$CONSUMER_KEY" ]]; then
  echo "✗ Could not extract Consumer Key for \"$APP_NAME\" from $SCRATCH." >&2
  echo "  Make sure the External Client App has been created in the scratch org." >&2
  exit 1
fi

INSTANCE_URL=$("$SF_BIN" org display --target-org "$SCRATCH" --json | node -e "process.stdout.write(JSON.parse(require('fs').readFileSync(0,'utf8')).result.instanceUrl)")

cat > "$REPO_ROOT/.env.local" <<EOF
# Autogenerated by sfdx/fetch-key.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Scratch org alias: $SCRATCH
# Instance URL:     $INSTANCE_URL
# App:              $APP_NAME
#
# Do NOT commit this file — it's in .gitignore.
PUBLIC_SF_CLIENT_ID=$CONSUMER_KEY
PUBLIC_SF_API_VERSION=63.0
PUBLIC_DEV_MOCK=0
PUBLIC_SF_SCRATCH_INSTANCE=$INSTANCE_URL
EOF

echo "✓ Wrote Consumer Key to .env.local"
echo "  Scratch org:  $INSTANCE_URL"
echo "  App:          $APP_NAME"
echo
echo "Next: npm run dev  →  http://127.0.0.1:4321/connect  →  My Domain → $INSTANCE_URL"
