#!/usr/bin/env bash
#
# QuantumShield scratch-org bootstrap.
# Creates (or reuses) a scratch org and deploys the scanner-target
# metadata (Apex classes, Remote Site Settings, Named Credentials).
# Does NOT deploy the External Client App — most Salesforce orgs
# require admin approval before Connected App / External Client App
# creation is permitted, so this step is manual and one-time. See the
# instructions printed at the end.
#
# Usage:  sfdx/bootstrap.sh [devhub-alias] [scratch-alias] [duration-days]
# Example: sfdx/bootstrap.sh opensf-prod qs-scan 7
#
set -euo pipefail

DEVHUB="${1:-opensf-prod}"
SCRATCH="${2:-qs-scan}"
DAYS="${3:-7}"
SFDX_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SFDX_DIR/.." && pwd)"

SF_BIN="${SF_BIN:-sf}"
if ! command -v "$SF_BIN" >/dev/null 2>&1; then
  if [[ -x "/c/Users/jeffk/AppData/Roaming/npm/sf" ]]; then
    SF_BIN="/c/Users/jeffk/AppData/Roaming/npm/sf"
  else
    echo "sf CLI not found on PATH" >&2
    exit 1
  fi
fi

cd "$SFDX_DIR"

echo "▸ Scratch org alias=$SCRATCH on DevHub=$DEVHUB (duration=${DAYS}d)"
if "$SF_BIN" org display --target-org "$SCRATCH" >/dev/null 2>&1; then
  echo "  scratch org '$SCRATCH' already exists — reusing."
else
  "$SF_BIN" org create scratch \
    --target-dev-hub "$DEVHUB" \
    --definition-file config/project-scratch-def.json \
    --alias "$SCRATCH" \
    --duration-days "$DAYS" \
    --set-default \
    --wait 20
fi

echo "▸ Deploying scanner-target metadata (Apex + Remote Sites + Named Credentials)"
"$SF_BIN" project deploy start \
  --target-org "$SCRATCH" \
  --source-dir force-app/main/default/classes \
  --source-dir force-app/main/default/remoteSiteSettings \
  --source-dir force-app/main/default/namedCredentials \
  --wait 20

echo "▸ Running readiness inspection"
"$SF_BIN" apex run --target-org "$SCRATCH" --file scripts/apex/seedInspect.apex

INSTANCE_URL=$("$SF_BIN" org display --target-org "$SCRATCH" --json | node -e "process.stdout.write(JSON.parse(require('fs').readFileSync(0,'utf8')).result.instanceUrl)")

# Preserve any existing Consumer Key in .env.local so the user doesn't
# have to re-paste after re-bootstrapping.
EXISTING_KEY=""
if [[ -f "$REPO_ROOT/.env.local" ]]; then
  EXISTING_KEY=$(grep -E '^PUBLIC_SF_CLIENT_ID=' "$REPO_ROOT/.env.local" | head -1 | cut -d= -f2- || true)
fi

cat > "$REPO_ROOT/.env.local" <<EOF
# Autogenerated by sfdx/bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Scratch org alias: $SCRATCH
# Instance URL:     $INSTANCE_URL
#
# Do NOT commit this file — it's in .gitignore.
# Paste your External Client App's Consumer Key below (see instructions on stdout).
PUBLIC_SF_CLIENT_ID=$EXISTING_KEY
PUBLIC_SF_API_VERSION=63.0
PUBLIC_DEV_MOCK=0
PUBLIC_SF_SCRATCH_INSTANCE=$INSTANCE_URL
EOF

echo
echo "✓ Scratch org + scanner-target metadata deployed."
echo "  Scratch org:  $INSTANCE_URL"
echo
echo "────────────────────────────────────────────────────────────────"
echo "NEXT — create the External Client App (one-time, manual):"
echo "────────────────────────────────────────────────────────────────"
echo
echo "1. Open the scratch org's App Manager:"
echo "     $SF_BIN org open --target-org $SCRATCH --path /lightning/setup/NavigationMenus/home"
echo "     Setup → App Manager → New External Client App (or New Connected App on older orgs)."
echo
echo "2. Configure the app:"
echo "     Name:           QuantumShield Scanner"
echo "     Contact email:  security@quantumshield.example"
echo "     Enable OAuth:   yes"
echo "     Require PKCE:   yes"
echo "     Callback URL:   http://127.0.0.1:4321/callback"
echo "     Scopes:         api, refresh_token, openid"
echo
echo "3. Add the CORS allowlist entry (one-time, same org):"
echo "     $SF_BIN org open --target-org $SCRATCH --path /lightning/setup/CorsAllowlistEntry/home"
echo "     Origin: http://127.0.0.1:4321"
echo
echo "4. Copy the Consumer Key, then:"
echo "     ./sfdx/fetch-key.sh qs-scan"
echo "   which will update .env.local. Or paste it into .env.local manually."
echo
echo "5. npm run dev  →  http://127.0.0.1:4321/connect  →  'My Domain'  →  $INSTANCE_URL"
